#!/usr/bin/env python3
"""One real Meta Model API call through the actual Assistant.handle() path.

Milestone under test (text workflow only):
    validated model extraction -> clarification when necessary ->
    deterministic availability/policy lookup -> supported answer.

The model is used for EXTRACTION ONLY. Operational facts (seat counts,
availability, hours) are produced by the deterministic tool from labelled
synthetic fixtures and rendered in code -- never generated by the model.

Safety properties of this harness:
  * --estimate performs NO network call and consumes NO credits.
  * --run requires BOTH the explicit --i-approve-spend flag and a key present
    in the local environment. The key is read from the environment only; it is
    never passed on the command line, printed, or written to evidence.
  * retries=0, one outstanding request, explicit input/output bounds and an
    explicit transport timeout.
  * No silent fallback: the live adapter raises rather than degrading to the
    mock or to another model. Execution stops at the first result or error.

Usage:
    python scripts/live_once.py --estimate
    MODEL_API_KEY=... python scripts/live_once.py --run --i-approve-spend
"""
from __future__ import annotations

import argparse
import subprocess
import json
import os
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.live_checks import evaluate_live_run, expected_from_fixtures  # noqa: E402
from app.model import LiveModelAdapter, make_model         # noqa: E402
from app.retrieval import load_pack                        # noqa: E402
from app.tools import AvailabilityTool                     # noqa: E402
from app.workflow import Assistant                         # noqa: E402

# --- the single synthetic enquiry under test --------------------------------
# Explicitly dated (no relative-date ambiguity), Hindi, inside the fixture
# coverage window. The expected date is therefore known in advance and is
# asserted below: a completed request that resolves the wrong date is NOT a
# successful workflow.
ENQUIRY = "28 अक्टूबर 2026 को दोपहर में कौन सी सीटें खाली हैं?"
EXPECTED_DATE = "2026-10-28"
EXPECTED_INTENT = "availability"
EXPECTED_LANG = "hi"

# --- verified provider facts (dev.meta.ai docs, checked 2 Nov 2026) ---------
BASE_URL = "https://api.meta.ai/v1"
MODEL_ID = "muse-spark-1.3"          # Standard mode. NOT the -contributor variant:
                                     # contributor pricing requires permitting Meta to
                                     # train on your content, i.e. a data-use change.
PRICE_IN_PER_M = 1.25                # USD / 1M input tokens
PRICE_OUT_PER_M = 4.25               # USD / 1M output tokens (reasoning billed at this rate)

# --- enforced bounds for this run -------------------------------------------
MAX_INPUT_CHARS = 2000
MAX_OUTPUT_TOKENS = 2048   # reasoning + visible JSON share this cap on Muse Spark
TIMEOUT_S = 20.0
DEADLINE_S = 25.0
RETRIES = 0
MAX_OUTSTANDING = 1
REASONING_EFFORT = "minimal"   # lowest supported; "none" is rejected by Muse Spark

_DEVANAGARI = re.compile(r"[ऀ-ॿ]")

# One key variable, loaded one way:
#   MODEL_API_KEY -- read from the process environment; before that, ROOT/.env is
#   loaded explicitly (python-dotenv, override=False) so a key already exported in
#   the shell always wins. The key is never accepted as a command-line argument.
KEY_VAR = "MODEL_API_KEY"


def load_key() -> str | None:
    try:
        from dotenv import load_dotenv
        load_dotenv(ROOT / ".env", override=False)
    except ImportError:
        pass                                    # .env loading is a convenience only
    return os.environ.get(KEY_VAR)


def redact(text: str, key: str | None) -> str:
    """Strip the key value and any bearer token from text before it is printed
    or written to evidence."""
    if not text:
        return text
    if key:
        text = text.replace(key, "[REDACTED_KEY]")
    text = re.sub(r"(?i)bearer\s+\S+", "Bearer [REDACTED]", text)
    text = re.sub(r"\bLLM_[A-Za-z0-9_\-]+", "[REDACTED_KEY]", text)
    return text


def git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                              capture_output=True, text=True, timeout=5).stdout.strip() or "unknown"
    except Exception:
        return "unknown"



def estimate_tokens(text: str) -> int:
    """Local heuristic ONLY -- not a provider token count. Devanagari tokenises
    far more densely than Latin text, so it is costed more conservatively."""
    dev = len(_DEVANAGARI.findall(text))
    other = len(text) - dev
    return max(1, round(dev / 1.0 + other / 3.5))


def build_assistant(api_key: str | None, *, verified: bool):
    tool = AvailabilityTool(ROOT / "fixtures")
    clock = tool.clock          # the tool's own fixture clock -- one clock, not two
    pack = load_pack(ROOT / "knowledge" / "policies.sample.json")
    model = make_model(
        "live",
        base_url=BASE_URL, model_id=MODEL_ID, api_key=api_key or "unset",
        verified=verified,
        retries=RETRIES, timeout_s=TIMEOUT_S, deadline_s=DEADLINE_S,
        max_output_tokens=MAX_OUTPUT_TOKENS, max_outstanding=MAX_OUTSTANDING,
        reasoning_effort=REASONING_EFFORT, max_input_chars=MAX_INPUT_CHARS,
    )
    return Assistant(pack=pack, tool=tool, model=model), clock, model


def fixture_label(clock) -> dict:
    occ = json.loads((ROOT / "fixtures" / "occupancy.json").read_text(encoding="utf-8"))
    return {
        "data_class": "SYNTHETIC FIXTURE -- not real Rasra Library data",
        "clock_class": "HISTORICAL FIXTURE CLOCK -- not the real current time",
        "fixture_clock_as_of": clock.as_of.isoformat(),
        "fixture_timezone": clock.tzname,
        "real_time_at_run_utc": datetime.now(timezone.utc).isoformat(),
        "coverage_from": occ["coverage"]["from"],
        "coverage_to": occ["coverage"]["to"],
        "enquiry_date_within_coverage":
            occ["coverage"]["from"] <= EXPECTED_DATE <= occ["coverage"]["to"],
    }


def do_estimate() -> int:
    assistant, clock, model = build_assistant(None, verified=False)
    payload = model._payload(ENQUIRY, now_iso=clock.as_of.isoformat(), prior=None)
    body = json.dumps(payload, ensure_ascii=False)
    in_tok = estimate_tokens(body)
    worst_out = MAX_OUTPUT_TOKENS
    cost_in = in_tok / 1_000_000 * PRICE_IN_PER_M
    worst_cost = cost_in + worst_out / 1_000_000 * PRICE_OUT_PER_M
    likely_out = 400          # minimal reasoning + a small strict-JSON object
    likely_cost = cost_in + likely_out / 1_000_000 * PRICE_OUT_PER_M

    out = {
        "mode": "ESTIMATE ONLY -- no network call made, no credits consumed",
        "provider": "Meta Model API",
        "base_url": BASE_URL,
        "endpoint": "/chat/completions",
        "model": MODEL_ID,
        "requests_to_be_made": 1,
        "bounds": {
            "retries": RETRIES, "max_outstanding": MAX_OUTSTANDING,
            "max_input_chars": MAX_INPUT_CHARS,
            "max_completion_tokens": MAX_OUTPUT_TOKENS,
            "reasoning_effort": REASONING_EFFORT,
            "transport_timeout_s": TIMEOUT_S, "overall_deadline_s": DEADLINE_S,
        },
        "enquiry": ENQUIRY,
        "expected": {"lang": EXPECTED_LANG, "intent": EXPECTED_INTENT, "date": EXPECTED_DATE},
        "fixture": fixture_label(clock),
        "estimated_input_tokens_heuristic": in_tok,
        "cost_estimate_usd": {
            "input": round(cost_in, 6),
            "likely_total": round(likely_cost, 6),
            "worst_case_total_at_output_cap": round(worst_cost, 6),
            "basis": "muse-spark-1.3 Standard: $1.25/M input, $4.25/M output; "
                     "reasoning tokens billed at the output rate",
            "caveat": "These are ESTIMATES, not a guaranteed bill: the input count "
                      "is a local heuristic, not a provider token count. Output "
                      "tokens are hard-capped at max_completion_tokens; input "
                      "tokens are not capped by the API, only by the enquiry's "
                      "2000-character bound.",
        },
        "exact_payload_to_be_sent": payload,
        "credential_handling": f"API key read only from {KEY_VAR} (shell env, or "
                               "ROOT/.env loaded explicitly without overriding the "
                               "shell); sent only in the Authorization header; "
                               "redacted from errors and evidence",
    }
    print(json.dumps(out, ensure_ascii=False, indent=2))
    return 0


def do_run() -> int:
    api_key = load_key()
    if not api_key:
        print(f"ERROR: no API key found. Put {KEY_VAR}=... in your shell environment "
              f"or in {ROOT / '.env'} (copy .env.example). The key is never accepted "
              "on the command line or in chat.", file=sys.stderr)
        return 2

    expected = expected_from_fixtures(ROOT / "fixtures", EXPECTED_DATE, "afternoon")

    assistant, clock, model = build_assistant(api_key, verified=True)
    started = time.monotonic()
    error = None
    resp = None
    try:
        resp = assistant.handle(ENQUIRY)            # the real handle() path
    except Exception as e:                          # stop at the FIRST error
        error = {"type": type(e).__name__, "message": redact(str(e), api_key)}
    latency_ms = round((time.monotonic() - started) * 1000, 1)

    meta = getattr(model, "last_meta", None) or {}
    resolved = (assistant.last_availability or {}) if resp else {}

    # Substantive acceptance: expectations independently re-derived from the raw
    # fixtures, response re-verified with a FRESH tool. A completed request with a
    # wrong date/slot/interval/count/seat set or an unsupported answer is NOT a
    # success.
    outcome = evaluate_live_run(
        resp, resolved, meta,
        expected=expected,
        recheck_tool=AvailabilityTool(ROOT / "fixtures"),
        pack=load_pack(ROOT / "knowledge" / "policies.sample.json"),
        error=error,
    )
    checks = outcome["checks"]

    record = {
        "result": "SUCCESS" if checks["workflow_successful"] else
                  ("COMPLETED_BUT_INCORRECT" if error is None else "ERROR"),
        "run_at_utc": datetime.now(timezone.utc).isoformat(),
        "code_commit": git_commit(),
        "provider": "Meta Model API",
        "base_url": BASE_URL,
        "model_requested": MODEL_ID,
        "model_returned": meta.get("model"),
        "transport": resp.get("transport") if resp else None,
        "simulated": resp.get("simulated") if resp else None,
        "latency_ms": latency_ms,
        "bounds": {"retries": RETRIES, "max_outstanding": MAX_OUTSTANDING,
                   "max_completion_tokens": MAX_OUTPUT_TOKENS,
                   "reasoning_effort": REASONING_EFFORT,
                   "transport_timeout_s": TIMEOUT_S, "overall_deadline_s": DEADLINE_S},
        "fixture": fixture_label(clock),
        "enquiry": ENQUIRY,
        "expected_from_fixtures": expected,
        "resolved_query": resolved or None,
        "tool_result": resp.get("availability") if resp else None,
        "supported_answer": resp.get("answer") if resp else None,
        "citations": resp.get("citations") if resp else None,
        "route": resp.get("route") if resp else None,
        "transparency_label": (resp.get("transparency") or {}).get("label") if resp else None,
        "response_id": meta.get("response_id"),
        "finish_reason": meta.get("finish_reason"),
        "usage": meta.get("usage"),
        "checks": checks,
        "consistency_issues": outcome["consistency_issues"],
        "error": error,
        "note": "Operational facts come from the deterministic tool over labelled "
                "synthetic fixtures; the model performed validated extraction only. "
                "Fixture availability is HISTORICAL demo data, not current real "
                "Rasra Library availability.",
    }

    usage = meta.get("usage") or {}
    if usage.get("prompt_tokens") is not None:
        record["billed_cost_usd_estimate"] = round(
            (usage["prompt_tokens"] or 0) / 1_000_000 * PRICE_IN_PER_M
            + (usage.get("completion_tokens") or 0) / 1_000_000 * PRICE_OUT_PER_M, 6)

    out_path = ROOT / "evidence" / "live_run.json"
    out_path.parent.mkdir(exist_ok=True)
    payload_text = redact(json.dumps(record, ensure_ascii=False, indent=2), api_key)
    out_path.write_text(payload_text, encoding="utf-8")
    print(payload_text)
    print(f"\nSanitised evidence written to {out_path}", file=sys.stderr)
    return 0 if checks["workflow_successful"] else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--estimate", action="store_true",
                   help="build the exact payload and cost estimate; makes NO call")
    g.add_argument("--run", action="store_true",
                   help="make exactly one real, billed call")
    ap.add_argument("--i-approve-spend", action="store_true",
                    help="required with --run; explicit approval to consume credits")
    a = ap.parse_args()

    if a.estimate:
        return do_estimate()
    if not a.i_approve_spend:
        print("REFUSED: --run consumes credits and requires --i-approve-spend.\n"
              "Run --estimate first to see the exact payload and cost.", file=sys.stderr)
        return 3
    return do_run()


if __name__ == "__main__":
    raise SystemExit(main())
